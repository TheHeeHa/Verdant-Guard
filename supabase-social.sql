create or replace function public.submit_feedback(
  p_type text,
  p_title text,
  p_message text,
  p_display_name text,
  p_session_key text
)
returns bigint language plpgsql security definer set search_path=public as $$
declare
  new_id bigint;
  effective_user uuid;
  effective_name text;
begin
  if p_type not in ('suggestion','bug','balance','accessibility','other') then raise exception 'Invalid feedback type'; end if;
  if char_length(trim(p_title)) not between 3 and 120 then raise exception 'Title must be 3 to 120 characters'; end if;
  if char_length(trim(p_message)) not between 5 and 2000 then raise exception 'Feedback must be 5 to 2000 characters'; end if;
  if char_length(trim(p_session_key)) not between 8 and 100 then raise exception 'Invalid feedback session'; end if;
  select id,display_name into effective_user,effective_name from public.profiles where id=auth.uid();
  effective_name=coalesce(nullif(trim(effective_name),''),nullif(left(trim(p_display_name),40),''),'Guest');
  insert into public.feedback_entries(submitter_id,submitter_name,session_key,type,title,message)
  values(effective_user,effective_name,left(trim(p_session_key),100),p_type,trim(p_title),trim(p_message))
  returning id into new_id;
  return new_id;
end $$;

