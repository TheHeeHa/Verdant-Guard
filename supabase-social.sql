create extension if not exists citext;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username citext not null unique,
  display_name text not null,
  bio text not null default '' check (char_length(bio)<=300),
  guardian_level integer not null default 1 check (guardian_level>=1),
  role text not null default 'player' check (role in ('player','admin','owner')),
  friend_requests_enabled boolean not null default false,
  cheats_enabled boolean not null default false,
  banned_until timestamptz,
  created_at timestamptz not null default now()
);

-- A username is taken only when every character matches exactly.
-- Capitalization, digits, punctuation, and spaces all count as differences.
alter table public.profiles alter column username type text using username::text;
drop index if exists public.profiles_username_unique_ci;

-- Usernames are case-insensitively unique from the moment signup begins.
-- Checking auth.users as well as profiles also covers accounts awaiting email confirmation.
create or replace function public.username_available(p_username text)
returns boolean language sql stable security definer set search_path=public,auth as $$
  select char_length(p_username) between 3 and 30
    and p_username ~ '[^[:space:]]'
    and not exists(select 1 from public.profiles where username=p_username)
    and not exists(select 1 from auth.users where raw_user_meta_data->>'username'=p_username);
$$;

-- Supabase password sign-in requires an email internally. The game resolves the
-- exact username first so players only need to enter username + password.
create or replace function public.login_email_for_username(p_username text)
returns text language sql stable security definer set search_path=public,auth as $$
  select u.email
  from public.profiles p
  join auth.users u on u.id=p.id
  where p.username=p_username
  limit 1;
$$;
revoke all on function public.login_email_for_username(text) from public;
grant execute on function public.login_email_for_username(text) to anon,authenticated;

create or replace function public.reject_duplicate_auth_username()
returns trigger language plpgsql security definer set search_path=public,auth as $$
declare requested text:=new.raw_user_meta_data->>'username';
begin
  if requested is null or char_length(requested) not between 3 and 30 or requested !~ '[^[:space:]]' then
    raise exception 'Username must contain 3 to 30 characters';
  end if;
  if exists(select 1 from auth.users where id<>new.id and raw_user_meta_data->>'username'=requested)
     or exists(select 1 from public.profiles where username=requested) then
    raise exception 'Username already taken';
  end if;
  return new;
end $$;

drop trigger if exists reject_duplicate_username_before_signup on auth.users;
create trigger reject_duplicate_username_before_signup before insert on auth.users
for each row execute function public.reject_duplicate_auth_username();

create or replace function public.create_signup_profile()
returns trigger language plpgsql security definer set search_path=public as $$
declare requested text:=new.raw_user_meta_data->>'username';
begin
  insert into public.profiles(id,username,display_name)
  values(new.id,requested,coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'),''),requested));
  return new;
end $$;

drop trigger if exists create_profile_after_signup on auth.users;
create trigger create_profile_after_signup after insert on auth.users
for each row execute function public.create_signup_profile();

-- Repair older confirmed or unconfirmed accounts that were created before the trigger existed.
insert into public.profiles(id,username,display_name)
select u.id,
       u.raw_user_meta_data->>'username',
       coalesce(nullif(u.raw_user_meta_data->>'display_name',''),u.raw_user_meta_data->>'username')
from auth.users u
where char_length(u.raw_user_meta_data->>'username') between 3 and 30
on conflict do nothing;

-- Remove stale public profiles left behind by manually deleted Auth users.
delete from public.profiles p
where not exists(select 1 from auth.users u where u.id=p.id);

create or replace function public.delete_my_account()
returns void language plpgsql security definer set search_path=public,auth as $$
begin
  delete from auth.users where id=auth.uid();
end $$;

