-- Verdant Guard social, moderation, and owner security setup.
-- Run once in Supabase SQL Editor as the project owner.
create extension if not exists citext;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username citext not null unique,
  display_name text not null,
  bio text not null default '' check (char_length(bio)<=300),
  guardian_level integer not null default 1 check (guardian_level>=1),
  role text not null default 'player' check (role in ('player','admin','owner')),
  friend_requests_enabled boolean not null default false,
  cheats_enabled boolean not null default false,
  banned_until timestamptz,
  created_at timestamptz not null default now()
);

-- Usernames are case-insensitively unique from the moment signup begins.
-- Checking auth.users as well as profiles also covers accounts awaiting email confirmation.
create or replace function public.username_available(p_username text)
returns boolean language sql stable security definer set search_path=public,auth as $$
  select char_length(trim(p_username)) between 3 and 30
    and not exists(select 1 from public.profiles where username=trim(p_username)::citext)
    and not exists(select 1 from auth.users where lower(raw_user_meta_data->>'username')=lower(trim(p_username)));
$$;

create or replace function public.reject_duplicate_auth_username()
returns trigger language plpgsql security definer set search_path=public,auth as $$
declare requested text:=trim(new.raw_user_meta_data->>'username');
begin
  if requested is null or char_length(requested) not between 3 and 30 then
    raise exception 'Username must contain 3 to 30 characters';
  end if;
  if exists(select 1 from auth.users where id<>new.id and lower(raw_user_meta_data->>'username')=lower(requested))
     or exists(select 1 from public.profiles where username=requested::citext) then
    raise exception 'Username already taken';
  end if;
  return new;
end $$;

drop trigger if exists reject_duplicate_username_before_signup on auth.users;
create trigger reject_duplicate_username_before_signup before insert on auth.users
for each row execute function public.reject_duplicate_auth_username();

create or replace function public.create_signup_profile()
returns trigger language plpgsql security definer set search_path=public as $$
declare requested text:=trim(new.raw_user_meta_data->>'username');
begin
  insert into public.profiles(id,username,display_name)
  values(new.id,requested,coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'),''),requested));
  return new;
end $$;

drop trigger if exists create_profile_after_signup on auth.users;
create trigger create_profile_after_signup after insert on auth.users
for each row execute function public.create_signup_profile();

-- Repair older confirmed or unconfirmed accounts that were created before the trigger existed.
insert into public.profiles(id,username,display_name)
select u.id,
       trim(u.raw_user_meta_data->>'username')::citext,
       coalesce(nullif(trim(u.raw_user_meta_data->>'display_name'),''),trim(u.raw_user_meta_data->>'username'))
from auth.users u
where char_length(trim(u.raw_user_meta_data->>'username')) between 3 and 30
on conflict do nothing;

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references public.profiles(id) on delete cascade,
  addressee_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted')),
  created_at timestamptz not null default now(),
  check (requester_id <> addressee_id)
);
create unique index if not exists friendships_pair_unique on public.friendships
  (least(requester_id,addressee_id), greatest(requester_id,addressee_id));

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  check (sender_id <> receiver_id)
);

create table if not exists public.blocks (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(blocker_id,blocked_id),
  check(blocker_id<>blocked_id)
);

create table if not exists public.custom_maps (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  description text not null default '',
  difficulty text not null default 'Unrated',
  visibility text not null default 'private' check (visibility in ('private','code','friends','public')),
  collaboration_mode text not null default 'owner' check (collaboration_mode in ('owner','friends','specific')),
  share_code citext unique,
  map_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.map_collaborators (
  map_id uuid not null references public.custom_maps(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(map_id,user_id)
);

create table if not exists public.groups (
  id uuid primary key default gen_random_uuid(),
  name citext not null unique,
  description text not null check(char_length(description) between 1 and 400),
  owner_id uuid not null references public.profiles(id),
  join_mode text not null default 'open' check(join_mode in ('open','approval')),
  member_count integer not null default 1,
  created_at timestamptz not null default now()
);
create table if not exists public.group_members (
  group_id uuid not null references public.groups(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check(role in ('member','owner')),
  status text not null default 'accepted' check(status in ('pending','accepted')),
  joined_at timestamptz not null default now(),
  primary key(group_id,user_id)
);
create table if not exists public.group_rooms (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.groups(id) on delete cascade,
  name text not null,
  visibility text not null default 'members' check(visibility in ('members','public')),
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);
create table if not exists public.group_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.group_rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check(char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);

create or replace function public.is_owner()
returns boolean language sql stable security definer set search_path=public
as $$ select auth.uid() = '49084e6c-317b-4df0-844c-3f16c960e998'::uuid $$;

create or replace function public.are_friends(a uuid,b uuid)
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from friendships where status='accepted' and ((requester_id=a and addressee_id=b) or (requester_id=b and addressee_id=a))) $$;
create or replace function public.is_group_member(g uuid)
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from group_members where group_id=g and user_id=auth.uid() and status='accepted') $$;
create or replace function public.is_group_owner(g uuid)
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from group_members where group_id=g and user_id=auth.uid() and role='owner' and status='accepted') $$;

