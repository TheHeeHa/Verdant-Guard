create or replace function public.owner_manage_user(p_target uuid,p_action text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_owner() then raise exception 'Owner access required'; end if;
  if p_target='49084e6c-317b-4df0-844c-3f16c960e998'::uuid then raise exception 'Owner cannot be modified'; end if;
  update profiles set
    banned_until=case when p_action='ban' then now()+interval '100 years' when p_action='pardon' then null else banned_until end,
    cheats_enabled=case when p_action='give_cheats' then true when p_action='remove_cheats' then false else cheats_enabled end,
    role=case when p_action='make_admin' then 'admin' when p_action='remove_admin' then 'player' else role end
  where id=p_target;
end $$;

create or replace function public.owner_rate_map(p_map uuid,p_difficulty text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_owner() then raise exception 'Owner access required'; end if;
  if p_difficulty not in ('Super Easy','Easy','Normal','Hard','Extreme','Insane') then raise exception 'Invalid difficulty'; end if;
  update custom_maps set difficulty=p_difficulty,updated_at=now() where id=p_map;
end $$;

create or replace function public.set_friend_requests(p_enabled boolean)
returns void language sql security definer set search_path=public as $$
  update profiles set friend_requests_enabled=p_enabled where id=auth.uid()
$$;

create or replace function public.update_my_profile(p_display_name text,p_bio text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if char_length(trim(p_display_name))<1 or char_length(p_bio)>300 then raise exception 'Invalid profile'; end if;
  update profiles set display_name=left(trim(p_display_name),40),bio=left(p_bio,300) where id=auth.uid();
end $$;

create or replace function public.set_my_guardian_level(p_level integer)
returns void language sql security definer set search_path=public as $$
  update profiles set guardian_level=greatest(guardian_level,least(10000,greatest(1,p_level))) where id=auth.uid()
$$;

create or replace function public.initialize_group()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into group_members(group_id,user_id,role,status) values(new.id,new.owner_id,'owner','accepted') on conflict do nothing;
  insert into group_rooms(group_id,name,visibility,created_by) values(new.id,'general','members',new.owner_id);
  return new;
end $$;
drop trigger if exists initialize_group_after_insert on public.groups;
create trigger initialize_group_after_insert after insert on public.groups for each row execute function public.initialize_group();

create or replace function public.join_group(p_group uuid,p_level integer)
returns void language plpgsql security definer set search_path=public as $$
declare mode text;
begin
  if p_level<5 then raise exception 'Guardian Level 5 required'; end if;
  update profiles set guardian_level=greatest(guardian_level,p_level) where id=auth.uid();
  select join_mode into mode from groups where id=p_group;
  insert into group_members(group_id,user_id,status) values(p_group,auth.uid(),case when mode='open' then 'accepted' else 'pending' end)
  on conflict(group_id,user_id) do nothing;
  if mode='open' then update groups set member_count=(select count(*) from group_members where group_id=p_group and status='accepted') where id=p_group; end if;
end $$;

create or replace function public.leave_group(p_group uuid)
returns void language plpgsql security definer set search_path=public as $$
begin
  if exists(select 1 from group_members where group_id=p_group and user_id=auth.uid() and role='owner') and (select count(*) from group_members where group_id=p_group and role='owner')=1 then raise exception 'Share or transfer ownership before leaving'; end if;
  delete from group_members where group_id=p_group and user_id=auth.uid();
  update groups set member_count=(select count(*) from group_members where group_id=p_group and status='accepted') where id=p_group;
end $$;

create or replace function public.manage_group_owner(p_group uuid,p_target uuid,p_action text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not exists(select 1 from group_members where group_id=p_group and user_id=auth.uid() and role='owner' and status='accepted') then raise exception 'Group owner required'; end if;
  if p_action='share' then update group_members set role='owner' where group_id=p_group and user_id=p_target and status='accepted';
  elsif p_action='transfer' then update group_members set role='member' where group_id=p_group and user_id=auth.uid(); update group_members set role='owner' where group_id=p_group and user_id=p_target and status='accepted'; update groups set owner_id=p_target where id=p_group;
  elsif p_action='remove' then update group_members set role='member' where group_id=p_group and user_id=p_target;
  else raise exception 'Invalid owner action'; end if;
end $$;

