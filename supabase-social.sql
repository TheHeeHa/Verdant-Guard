create or replace function public.owner_send_broadcast(p_scope text,p_target text,p_message text,p_font text,p_color text)
returns bigint language plpgsql security definer set search_path=public as $$
declare
  new_id bigint;
  user_target uuid;
  group_target uuid;
begin
  if not public.is_owner() then raise exception 'Owner access required'; end if;
  if p_scope not in ('global','user','group') then raise exception 'Invalid message audience'; end if;
  if char_length(trim(p_message)) not between 1 and 500 then raise exception 'Message must be 1 to 500 characters'; end if;
  if p_font not in ('Georgia','Arial','Verdana','monospace') then raise exception 'Invalid font'; end if;
  if p_color !~ '^#[0-9A-Fa-f]{6}$' then raise exception 'Invalid color'; end if;
  if p_scope='user' then
    select id into user_target from public.profiles where lower(username)=lower(trim(p_target));
    if user_target is null then raise exception 'Username not found'; end if;
  elsif p_scope='group' then
    select id into group_target from public.groups where lower(name)=lower(trim(p_target));
    if group_target is null then raise exception 'Group not found'; end if;
  end if;
  insert into public.owner_broadcasts(owner_id,scope,target_user,target_group,message,font_family,color)
  values(auth.uid(),p_scope,user_target,group_target,trim(p_message),p_font,p_color)
  returning id into new_id;
  return new_id;
end $$;

create or replace function public.owner_manage_user(p_target uuid,p_action text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_owner() then raise exception 'Owner access required'; end if;
  if p_target='49084e6c-317b-4df0-844c-3f16c960e998'::uuid then raise exception 'Owner cannot be modified'; end if;
  if p_action not in ('ban','pardon','give_cheats','remove_cheats','make_admin','remove_admin') then raise exception 'Invalid owner action'; end if;
  update profiles set
    banned_until=case when p_action='ban' then now()+interval '100 years' when p_action='pardon' then null else banned_until end,
    cheats_enabled=case when p_action='give_cheats' then true when p_action='remove_cheats' then false else cheats_enabled end,
    role=case when p_action='make_admin' then 'admin' when p_action='remove_admin' then 'player' else role end
  where id=p_target;
  if p_action='make_admin' then insert into public.player_notifications(user_id,type,message) values(p_target,'made_admin','You are now a Verdant Guard admin.'); end if;
  if p_action='give_cheats' then insert into public.player_notifications(user_id,type,message) values(p_target,'cheats_given','The owner gave your account cheat-panel access.'); end if;
end $$;

